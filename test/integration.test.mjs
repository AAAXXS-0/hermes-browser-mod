import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { parse } from 'yaml';
import { ROOT, RUNTIME, VERSION } from '../src/paths.mjs';
const exec = promisify(execFile);
test('公开安装 CLI：自定义含空格路径、错误前置检查、安装撤销与配置保留', async () => {
  const fixture = await fs.mkdtemp(path.join(RUNTIME, 'public-integration-'));
  const desktop = path.join(fixture, 'desktop with spaces');
  const runtimeRoot = path.join(desktop, 'data'), home = path.join(runtimeRoot, 'hermes-home');
  const toolRuntime = path.join(fixture, 'mod-runtime'), build = path.join(toolRuntime, 'native-ui', 'V' + VERSION);
  await fs.mkdir(home, { recursive: true });
  await fs.mkdir(path.join(runtimeRoot, 'ui'), { recursive: true });
  await fs.mkdir(build, { recursive: true });
  const original = '# preserve comment\nplugins:\n  enabled: [other-plugin]\nmcp_servers:\n  other-server: {command: existing}\nmodel: fixture\n';
  const originalUi = '{"schemaVersion":1,"uiVersion":"0.9.0","path":"existing-ui"}\n';
  await fs.writeFile(path.join(home, 'config.yaml'), original);
  await fs.writeFile(path.join(runtimeRoot, 'ui/current.json'), originalUi);
  await fs.writeFile(path.join(build, 'index.html'), '<script src="assets/main.js"></script>');
  const metadata = { modVersion: VERSION, desktopVersion: '0.9.0', desktopCommit: '270f6ba796a291cf1397b63dee5cd697cb0c9cdf' };
  await fs.writeFile(path.join(build, 'browser-mod-build.json'), JSON.stringify(metadata));
  const env = { ...process.env, HBM_RUNTIME_DIR: toolRuntime, HERMES_HOME: home };
  delete env.HBM_HERMES_DESKTOP_ROOT; delete env.HBM_HERMES_RUNTIME_ROOT;
  const cli = (mode, ...flags) => exec(process.execPath, [path.join(ROOT, 'src/integration.mjs'), mode, ...flags], { env, windowsHide: true });
  await assert.rejects(cli('install'), error => error.stderr.includes('必须指定'));
  assert.equal(await fs.readFile(path.join(home, 'config.yaml'), 'utf8'), original);
  const flags = ['--desktop-root', desktop, '--runtime-root', runtimeRoot, '--home', home];
  await fs.writeFile(path.join(build, 'browser-mod-build.json'), JSON.stringify({ ...metadata, modVersion: '0.0.0' }));
  await assert.rejects(cli('install', ...flags), error => error.stderr.includes('匹配'));
  assert.equal(await fs.readFile(path.join(runtimeRoot, 'ui/current.json'), 'utf8'), originalUi);
  await fs.writeFile(path.join(build, 'browser-mod-build.json'), JSON.stringify(metadata));
  await cli('install', ...flags);
  const installed = parse(await fs.readFile(path.join(home, 'config.yaml'), 'utf8'));
  assert.deepEqual(installed.plugins.enabled, ['other-plugin', 'hermes-browser-mod']);
  assert.equal(installed.mcp_servers['other-server'].command, 'existing');
  assert.equal(JSON.parse(await fs.readFile(path.join(runtimeRoot, 'ui/current.json'), 'utf8')).path, build);
  await cli('remove', ...flags);
  const removed = await fs.readFile(path.join(home, 'config.yaml'), 'utf8');
  assert.ok(removed.includes('# preserve comment'));
  assert.deepEqual(parse(removed).plugins.enabled, ['other-plugin']);
  assert.equal(await fs.readFile(path.join(runtimeRoot, 'ui/current.json'), 'utf8'), originalUi);
});
