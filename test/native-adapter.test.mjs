import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { installNative } from '../src/native-adapter.mjs';
import { RUNTIME, VERSION } from '../src/paths.mjs';
test('原生界面副本单独启用与撤销，完整恢复原指向，拒绝覆盖后续更新', async () => {
  const dir = path.join(RUNTIME, `native-adapter-test-${Date.now()}`);
  const runtimeRoot = path.join(dir, 'runtime'), recordDir = path.join(dir, 'record'), buildDir = path.join(dir, 'build');
  await fs.mkdir(path.join(runtimeRoot, 'ui'), { recursive: true });
  await fs.mkdir(buildDir, { recursive: true });
  const current = path.join(runtimeRoot, 'ui/current.json');
  const original = '{"schemaVersion":1,"uiVersion":"0.9.0-original","path":"original-package"}\n';
  await fs.writeFile(current, original);
  await fs.writeFile(path.join(buildDir, 'browser-mod-build.json'), JSON.stringify({ desktopVersion: '0.9.0', desktopCommit: '270f6ba796a291cf1397b63dee5cd697cb0c9cdf', modVersion: VERSION }));
  await fs.writeFile(path.join(buildDir, 'index.html'), '<script src="assets/main.js"></script>');
  await installNative('install', { runtimeRoot, recordDir, buildDir });
  assert.equal(JSON.parse(await fs.readFile(current, 'utf8')).source, 'local-browser-mod');
  await installNative('remove', { runtimeRoot, recordDir, buildDir });
  assert.equal(await fs.readFile(current, 'utf8'), original);
  await fs.unlink(current);
  await installNative('install', { runtimeRoot, recordDir, buildDir });
  const installed = await fs.readFile(current, 'utf8');
  await fs.writeFile(current, '{"uiVersion":"updated-by-user"}');
  await assert.rejects(installNative('remove', { runtimeRoot, recordDir, buildDir }), /其他更新/);
  await fs.writeFile(current, installed);
  await installNative('remove', { runtimeRoot, recordDir, buildDir });
  await assert.rejects(fs.access(current));
});
